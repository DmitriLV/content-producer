OUTPUT_PATH = Path(__file__).resolve().parent / "Content_Producer_AI_System_Card.docx"

ACCENT = RGBColor(0x4F, 0x6D, 0xF5)
MUTED = RGBColor(0x6B, 0x72, 0x80)
DARK = RGBColor(0x23, 0x26, 0x2F)


def shade_cell(cell, color_hex: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), color_hex)
    tc_pr.append(shd)


def shade_paragraph(paragraph, color_hex: str) -> None:
    p_pr = paragraph._p.get_or_add_pPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), color_hex)
    p_pr.append(shd)


def add_quote_block(doc: Document, text: str) -> None:
    """Добавляет блок текста в стиле 'цитата/код' с серым фоном и моноширинным шрифтом."""
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.5)
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(10)
    shade_paragraph(p, "F2F2F7")
    run = p.add_run(text)
    run.font.name = "Consolas"
    run.font.size = Pt(10)
    run.font.color.rgb = DARK


def add_bullets(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def add_metrics_table(doc: Document, rows: list[tuple[str, str, str]]) -> None:
    table = doc.add_table(rows=1, cols=3)
    table.style = "Light Grid Accent 1"
    hdr = table.rows[0].cells
    hdr[0].text = "Метрика"
    hdr[1].text = "Целевое значение"
    hdr[2].text = "Комментарий"
    for cell in hdr:
        for p in cell.paragraphs:
            for r in p.runs:
                r.font.bold = True
    for name, target, comment in rows:
        cells = table.add_row().cells
        cells[0].text = name
        cells[1].text = target
        cells[2].text = comment
    doc.add_paragraph()


def set_base_style(doc: Document) -> None:
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)
    style.font.color.rgb = DARK

    for i in range(1, 4):
        h = doc.styles[f"Heading {i}"]
        h.font.color.rgb = ACCENT


